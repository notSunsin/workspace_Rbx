local function NormalizeOdds(p2) -- Line: 2070
    local Items = p2.Items;
    local v3 = 0;

    for _, v in Items do
        v3 = v3 + v.ItemOdd;
    end;

    for i, v in Items do
        v.NormalizedOdd = v.ItemOdd / v3 * 100;
        v.Name = i;
    end;

    p2.TotalOdds = v3;

    return p2;
end;

